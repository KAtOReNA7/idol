import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {gzipSync,gunzipSync} from 'node:zlib';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
export function renderSnapshotFallback(source){
 // Compress the original bytes, never a parsed/re-serialized approximation.
 const compressed=gzipSync(source,{level:9});
 compressed.fill(0,4,8); // Deterministic mtime.
 compressed[9]=255; // Platform-independent gzip OS header.
 if(!gunzipSync(compressed).equals(source))throw new Error('Snapshot compression integrity check failed');
 const sha256=createHash('sha256').update(source).digest('hex');
 return [
  '// Generated by scripts/build-snapshot-fallback.mjs. Do not edit.',
  '// Lossless server-only packaging; data/snapshot.json remains authoritative.',
  "import 'server-only';",
  `export const snapshotByteLength = ${source.length};`,
  `export const snapshotSha256 = ${JSON.stringify(sha256)};`,
  `export const snapshotGzipBase64 = ${JSON.stringify(compressed.toString('base64'))};`,
  '',
 ].join('\n');
}
export function generate({check=false,sourcePath=path.join(root,'data/snapshot.json'),destinationPath=path.join(root,'data/snapshot-fallback.generated.ts')}={}){
 const output=renderSnapshotFallback(readFileSync(sourcePath));
 if(check){
  let current;try{current=readFileSync(destinationPath,'utf8');}catch{}
  if(current!==output)throw new Error('Stale fallback snapshot: run node scripts/build-snapshot-fallback.mjs');
 }else{
  mkdirSync(path.dirname(destinationPath),{recursive:true});
  writeFileSync(destinationPath,output);
 }
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))generate({check:process.argv.includes('--check')});
