'use strict';
const assert=require('node:assert/strict'),crypto=require('node:crypto');
const EVENT_ID='e-triples-assemble24-complete-phase';
const SOURCE_ID='es-triples-assemble24-soompi-20240508';
const SOURCE_PATH='HANDOFF/timeline-corrections/triples-assemble24-source.json';
const URL='https://www.soompi.com/article/1654800wpp/triples-announces-comeback-date-for-full-group-return-with-assemble24';
const stable=v=>Array.isArray(v)?v.map(stable):v&&typeof v==='object'?Object.fromEntries(Object.keys(v).sort().map(k=>[k,stable(v[k])])):v;
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
const digest=v=>hash(JSON.stringify(stable(v)));
const fields=['eventDate','scopeNote','sources','summary','workIds'];
// These are three explicitly reviewed successors, not a general hash exemption.
// Historical adoption and source audits consume the verified before object;
// current data must equal the independently recorded after object exactly.
function validateCorrectionChain({corrections,events,ledger,readBytes,snapshot}){
 assert.equal(corrections.length,3,'only the three reviewed corrections are allowed');
 const c=corrections[0];
 assert.equal(c.schemaVersion,1);assert.equal(c.correctionId,'triples-assemble24-20261016');
 assert.equal(c.eventId,EVENT_ID);assert.equal(c.slug,'triples');
 assert.equal(c.baseCommit,'228ed8e4cf84a0078bcc09d48bbce374e777f7ad');
 assert.equal(c.historicalLedger,'HANDOFF/batch-f/integration-ledger.json');
 assert.equal(c.historicalLedgerSha256,'177e6a6236c647a9ae5730f7d80df03333f0f13fa197c9263ded6cd4391e7d7d','historical Batch F bytes are immutable');
 assert.equal(c.historicalManifestSha256,'afc292a22593be1ae4bdfc08eab2c20efc0e365545cdbd2df46d3749562b3d99','historical Batch F bytes are immutable');
 assert.equal(c.historicalSourceIndexSha256,'7b7bb472a912b1116c5b447893b00bf33c7c4ab904dd8aa3d680f7cdf7e1ee2c','historical Batch F bytes are immutable');
 assert.equal(hash(readBytes(c.historicalLedger)),c.historicalLedgerSha256);
 assert.equal(hash(readBytes('HANDOFF/batch-f/original-manifest.json')),c.historicalManifestSha256);
 assert.equal(hash(readBytes('HANDOFF/batch-f/source-index.json')),c.historicalSourceIndexSha256);
 const row=ledger.events.find(e=>e.eventId===EVENT_ID);assert.ok(row);
 assert.equal(c.historicalAdoptedSha256,row.adoptedEventSha256);
 assert.equal(c.beforeSha256,row.adoptedEventSha256);assert.equal(digest(c.before),c.beforeSha256);
 assert.equal(c.before.id,EVENT_ID);assert.equal(c.after.id,EVENT_ID);
 assert.equal(digest(c.after),c.afterSha256);assert.deepEqual(events.get(EVENT_ID),c.after);
 assert.deepEqual(c.allowedFields,fields);
 const changed=[...new Set([...Object.keys(c.before),...Object.keys(c.after)])].filter(k=>digest(c.before[k]??null)!==digest(c.after[k]??null)).sort();
 assert.deepEqual(changed,fields,'no out-of-scope fields may change');
 assert.deepEqual(Object.keys(c.before).sort(),Object.keys(c.after).sort());
 assert.deepEqual(c.diff,fields.map(field=>({field,before:c.before[field],after:c.after[field]})));
 assert.deepEqual(c.after.eventDate,{value:'2024-05-08',precision:'day'});
 assert.deepEqual(c.after.workIds,['rec28ldfRTrCjG']);assert.deepEqual(c.after.memberIds,[]);
 assert.equal(c.after.groupId,'rec28ldfRTiCtw');assert.equal(c.after.releaseKey,'triples-assemble24');
 assert.ok(c.after.scopeNote.startsWith(c.before.scopeNote),'retain historical scope and append correction');
 assert.deepEqual(c.after.sources.slice(0,-1),c.before.sources,'retain original Bugs source unchanged');
 assert.equal(c.after.sources.length,c.before.sources.length+1);
 const source=c.after.sources.at(-1);
 assert.equal(source.id,SOURCE_ID);assert.equal(source.url,URL);assert.equal(source.evidenceRef,SOURCE_PATH);
 assert.deepEqual(source.sourcePublishedAt,{value:'2024-04-14',precision:'day'});
 assert.equal(c.evidence.path,SOURCE_PATH);const bytes=readBytes(SOURCE_PATH);
 assert.equal(hash(bytes),c.evidence.sha256);const proof=JSON.parse(bytes);
 assert.equal(proof.url,URL);assert.equal(proof.originalArticleDate,'2024-04-14');
 assert.equal(proof.relevantUpdateDate,'2024-05-08');assert.equal(proof.relevantUpdateTimezone,'Asia/Seoul');
 assert.ok(proof.evidenceLocation);assert.ok(proof.paraphrase);assert.ok(proof.readMethod);
 assert.deepEqual(proof.findings,{releaseTitle:'ASSEMBLE24',releaseDate:'2024-05-08',releaseLocalTime:'18:00',timezone:'Asia/Seoul',titleTrack:'Girls Never Die',mvReleasedTogether:true,groupScope:'24人完整体'});
 const matches=snapshot.tables.works.records.filter(w=>w.recordId==='rec28ldfRTrCjG');assert.equal(matches.length,1);
 const w=matches[0],identity={recordId:w.recordId,groupIds:w.fields.fld2wy1cqw.map(g=>g.recordId),url:w.fields.fldhBWXBZE[0]?.url,song:w.fields.fld6ahf75U,officialTitle:w.fields.fld6nT26GF};
 const pinned={recordId:'rec28ldfRTrCjG',groupIds:['rec28ldfRTiCtw'],url:'https://www.youtube.com/watch?v=2tda_TCjz8w',song:'Girls Never Die',officialTitle:"tripleS(트리플에스) 'Girls Never Die' Official MV"};
 assert.deepEqual(c.workIdentity,pinned);assert.deepEqual(identity,pinned,'existing work identity must not drift');
 const b=corrections[1],badId='e-badvillain-official-debut';
 assert.equal(b.schemaVersion,1);assert.equal(b.correctionId,'badvillain-overstep-20261018');
 assert.equal(b.eventId,badId);assert.equal(b.slug,'badvillain');
 const badRow=ledger.events.find(row=>row.eventId===badId);assert.ok(badRow);
 assert.equal(digest(b.before),badRow.adoptedEventSha256);assert.equal(b.beforeSha256,badRow.adoptedEventSha256);
 assert.equal(digest(b.after),b.afterSha256);assert.deepEqual(events.get(badId),b.after);
 assert.deepEqual(b.allowedFields,['eventDate','scopeNote','sources','summary']);
 assert.deepEqual(Object.keys(b.before).filter(key=>digest(b.before[key]??null)!==digest(b.after[key]??null)).sort(),b.allowedFields);
 assert.deepEqual(Object.keys(b.before).sort(),Object.keys(b.after).sort());
 assert.deepEqual(b.after.eventDate,{value:'2024-06-03',precision:'day'});
 assert.deepEqual(b.before.eventDate,{value:'2024-06',precision:'month'});
 assert.deepEqual(b.after.workIds,b.before.workIds);assert.deepEqual(b.after.memberIds,b.before.memberIds);
 assert.deepEqual(b.after.sources.slice(0,-1),b.before.sources);
 const badSource=b.after.sources.at(-1),badPath='evidence/approved-visual-repairs/badvillain-overstep-date.json';
 assert.equal(badSource.id,'visual-repair-badvillain-overstep-bugs');
 assert.equal(badSource.url,'https://music.bugs.co.kr/album/4102279?wl_ref=M_contents_01_07');
 assert.equal(badSource.evidenceRef,badPath);assert.equal(b.evidence.path,badPath);
 const badBytes=readBytes(badPath);assert.equal(hash(badBytes),b.evidence.sha256);
 const badProof=JSON.parse(badBytes);assert.equal(badProof.eventId,badId);assert.equal(badProof.url,badSource.url);
 assert.equal(badProof.dateMetadata,'2024.06.03');assert.equal(badProof.excerpt,'BADVILLAIN(배드빌런), 6월 3일 데뷔 앨범 [OVERSTEP] 발표');
 const badDoc=JSON.parse(readBytes('data/artist-timelines/badvillain.json'));
 assert.equal(hash(readBytes('data/artist-timelines/badvillain.json')),b.afterDocumentSha256);
 assert.deepEqual(badDoc.gaps,b.afterGaps);
 assert.deepEqual(b.afterGaps,b.beforeGaps.filter(g=>!g.startsWith('6月3日精确出道日')&&!g.startsWith('OVERSTEP正式出道仅保留')));
 badDoc.events=badDoc.events.map(event=>event.id===badId?b.before:event);badDoc.gaps=b.beforeGaps;
 assert.equal(hash(JSON.stringify(badDoc,null,2)+'\n'),b.beforeDocumentSha256);
 const m=corrections[2],madeinId='e-madein-rise-release-carrier-hold';
 assert.equal(m.schemaVersion,1);assert.equal(m.correctionId,'madein-rise-20261018');assert.equal(m.eventId,madeinId);assert.equal(m.slug,'madein');
 const madeinRow=ledger.events.find(row=>row.eventId===madeinId);assert.ok(madeinRow);
 assert.equal(digest(m.before),madeinRow.adoptedEventSha256);assert.equal(m.beforeSha256,madeinRow.adoptedEventSha256);
 assert.equal(digest(m.after),m.afterSha256);assert.deepEqual(events.get(madeinId),m.after);
 assert.deepEqual(m.allowedFields,['eventDate','holdReasons','reviewStatus','scopeNote','sources','status','summary','title']);
 assert.deepEqual(Object.keys(m.before).sort(),Object.keys(m.after).sort());
 assert.deepEqual(Object.keys(m.before).filter(key=>digest(m.before[key]??null)!==digest(m.after[key]??null)).sort(),m.allowedFields);
 assert.equal(m.before.reviewStatus,'hold');assert.equal(m.before.eventDate,null);assert.equal(m.before.status,'uncertain');
 assert.equal(m.after.reviewStatus,'ready');assert.equal(m.after.status,'confirmed');assert.deepEqual(m.after.holdReasons,[]);
 assert.deepEqual(m.after.eventDate,{value:'2024-09-03',precision:'day'});assert.equal(m.after.groupId,'rec28ldfRTiCzI');assert.equal(m.after.releaseKey,'madein-rise');
 assert.deepEqual(m.after.workIds,['rec28ldfRTrCvB','rec28ldfRTrCzF','rec28ldfRTrCDJ']);assert.deepEqual(m.after.memberIds,[]);
 assert.deepEqual(m.after.sources.slice(0,-1),m.before.sources);
 const madeinSource=m.after.sources.at(-1),madeinPath='evidence/approved-visual-repairs/madein-rise-distribution.json';
 assert.equal(madeinSource.id,'visual-repair-madein-rise-apple');assert.equal(madeinSource.url,'https://music.apple.com/us/album/rise-ep/1766046545');
 assert.equal(madeinSource.evidenceRef,madeinPath);assert.equal(m.evidence.path,madeinPath);
 const madeinBytes=readBytes(madeinPath);assert.equal(hash(madeinBytes),m.evidence.sha256);const madeinProof=JSON.parse(madeinBytes);
 assert.equal(madeinProof.eventId,madeinId);assert.equal(madeinProof.albumId,'1766046545');assert.equal(madeinProof.artist,'MADEIN');assert.equal(madeinProof.label,'143 Entertainment');
 assert.equal(madeinProof.releaseDate,'2024-09-03');assert.equal(madeinProof.format,'digital EP');assert.equal(madeinProof.artistCatalogue,'https://madein-official.net/discography/rise/');
 assert.deepEqual(madeinProof.tracks.map(t=>t.title),['UNO','DADARIDA','DOPAMINE','TIMELINE']);assert.ok(madeinProof.tracks.every(t=>t.date==='2024-09-03'&&t.audioUrl.startsWith('https://audio-ssl.itunes.apple.com/')));
 assert.equal(madeinProof.previewVerification.httpStatus,200);assert.equal(madeinProof.previewVerification.contentType,'audio/x-m4p');assert.equal(madeinProof.previewVerification.bytes,1038074);assert.match(madeinProof.previewVerification.sha256,/^[0-9a-f]{64}$/);
 const madeinDoc=JSON.parse(readBytes('data/artist-timelines/madein.json'));assert.equal(hash(readBytes('data/artist-timelines/madein.json')),m.afterDocumentSha256);
 assert.deepEqual(madeinDoc.gaps,m.afterGaps);assert.deepEqual(m.afterGaps,m.beforeGaps.filter(g=>!g.startsWith('《RISE》仅有官方目录')&&!g.startsWith('RISE旧carrier hold')));
 madeinDoc.events=madeinDoc.events.map(event=>event.id===madeinId?m.before:event);madeinDoc.gaps=m.beforeGaps;
 assert.equal(hash(JSON.stringify(madeinDoc,null,2)+'\n'),m.beforeDocumentSha256);
 const {historical}=require('./timeline-category-corrections.cjs').validateCategoryCorrections({events,ledger,readBytes});
 historical.set(EVENT_ID,c.before);historical.set(badId,b.before);historical.set(madeinId,m.before);
 for(const row of ledger.events){assert.ok(historical.has(row.eventId));assert.equal(digest(historical.get(row.eventId)),row.adoptedEventSha256,row.eventId);}
 return historical;
}
